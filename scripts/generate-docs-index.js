#!/usr/bin/env node

import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const repoRoot = path.resolve(__dirname, '..');
const docsDir = path.join(repoRoot, 'docs');
const outputPath = path.join(docsDir, 'DOCS-INDEX.md');

function toTitle(markdown, fallbackName) {
  const lines = markdown.split('\n');
  const heading = lines.find(line => line.startsWith('# '));
  if (heading) return heading.slice(2).trim();
  return fallbackName.replace(/\.md$/i, '').replace(/-/g, ' ');
}

async function main() {
  const entries = await readdir(docsDir, { withFileTypes: true });
  const markdownFiles = entries
    .filter(entry => entry.isFile())
    .map(entry => entry.name)
    .filter(name => name.endsWith('.md'))
    .filter(name => name !== 'DOCS-INDEX.md')
    .sort((a, b) => a.localeCompare(b, 'en'));

  const docs = await Promise.all(
    markdownFiles.map(async fileName => {
      const fullPath = path.join(docsDir, fileName);
      const content = await readFile(fullPath, 'utf8');
      return {
        fileName,
        title: toTitle(content, fileName),
      };
    }),
  );

  const body = [
    '# DOCS-INDEX',
    '',
    '> Generated by `npm run docs:index`. Edit the source docs, not this file.',
    '',
    '| File | Title |',
    '|---|---|',
    ...docs.map(doc => `| [${doc.fileName}](${doc.fileName}) | ${doc.title.replace(/\|/g, '\\|')} |`),
    '',
  ].join('\n');

  await writeFile(outputPath, body, 'utf8');
  console.log(`Updated ${path.relative(repoRoot, outputPath)}`);
}

main().catch(error => {
  console.error(error.message);
  process.exitCode = 1;
});
